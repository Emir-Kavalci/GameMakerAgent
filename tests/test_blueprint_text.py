COMPONENTS = [
    {"name": "Root", "class": "SceneComponent", "parent": "", "native": True, "inherited": True},
    {"name": "Mesh", "class": "StaticMeshComponent", "parent": "Root", "native": False, "inherited": False},
]


def main():
    reader = blueprint_text.BlueprintReader(T3D, ["MyGame"], COMPONENTS, {"CoinValue": "25.0"})
    text = reader.text()
    lines = text.splitlines()
    only_function = reader.text(only="GetBonus")
    long_text = reader.text(max_lines=5)
    checks = [
        ("parse_struct keeps nested values", blueprint_text.parse_struct('(A=1,B="x,y",C=(D=2))') == {"A": "1", "B": '"x,y"', "C": "(D=2)"}),
        ("text_value reads NSLOCTEXT", blueprint_text.text_value('NSLOCTEXT("K2Node", "Target", "Target")') == "Target"),
        ("text_value reads a nested category",
         blueprint_text.text_value('LOCGEN_FORMAT_ORDERED(NSLOCTEXT("", "1", "{0}|{1}"), NSLOCTEXT("", "2", "Movement"), NSLOCTEXT("", "3", "Jump"))') == "Movement|Jump"),
        ("short_name strips paths and _C", blueprint_text.short_name("/Script/Engine.BlueprintGeneratedClass'/Game/A/BP_X.BP_X_C'") == "BP_X"),
        ("parent class is marked as this project's C++", "Parent class: CoinBase (C++ in this project: /Script/MyGame.CoinBase)" in lines),
        ("components keep their hierarchy and origin", "  - Root (SceneComponent) [from C++ parent class]" in lines and "    - Mesh (StaticMeshComponent)" in lines),
        ("variables show type, default and editability", "- CoinValue: Float = 25.0 (instance editable)" in lines),
        ("array variables are named as arrays", "- Pickups: Array of Actor" in lines),
        ("an event declared in C++ is marked, without OutputDelegate",
         "Event OnCollected [event declared in C++] (Collector: Actor)" in lines),
        ("a reroute node is skipped and the condition is written as an expression", "  Branch(Condition = CoinValue > 10.0)" in lines),
        ("branch outputs are labelled", "    True:" in lines and "    False:" not in lines),
        ("a comment box is shown above the step inside it", "      // Give the reward" in lines),
        ("a C++ call is marked and untouched defaults are left out", "      CoinBase.AddScore [C++](Amount = 5)" in lines),
        ("an unused event is left out", "Tick" not in text),
        ("function graphs show their inputs and return values",
         "Function GetBonus (Multiplier: Float)" in lines and "  Return (Bonus = Multiplier)" in lines),
        ("one graph can be read on its own", only_function is not None and "Parent class" not in only_function and "GetBonus" in only_function),
        ("an unknown graph gives None", reader.text(only="NoSuchGraph") is None),
        ("graph names are listed", reader.graph_names() == ["EventGraph", "GetBonus"]),
        ("a long Blueprint lists its graphs instead", "Read one graph at a time" in long_text and "- GetBonus (" in long_text),
    ]
    failed = 0
    for name, passed in checks:
        print(("ok    " if passed else "FAIL  ") + name)
        failed += not passed
    if failed:
        print(text)
        print("Some Blueprint text tests failed.")
        sys.exit(1)
    print("All Blueprint text tests passed.")


if __name__ == "__main__":
    main()
